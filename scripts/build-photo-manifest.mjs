#!/usr/bin/env node
/** Regenerates src/lib/photos.ts from the JPEGs in public/photos.
 *  Run after adding a photo so next/image has real dimensions (no layout shift)
 *  and nothing can be upscaled past its native width (BUILD_BRIEF §4.5). */
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";

const DIR = "public/photos";
const files = readdirSync(DIR).filter((f) => /\.jpe?g$/i.test(f)).sort();

const rows = [];
for (const f of files) {
  const slug = f.replace(/\.jpe?g$/i, "");
  const { width, height } = await sharp(join(DIR, f)).metadata();
  const orientation = width > height ? "landscape" : width < height ? "portrait" : "square";
  rows.push(`  "${slug}": { slug: "${slug}", width: ${width}, height: ${height}, orientation: "${orientation}" },`);
}

writeFileSync(
  "src/lib/photos.ts",
  `// AUTO-GENERATED by scripts/build-photo-manifest.mjs — do not edit by hand.
// Native dimensions of every supplied photo, so next/image never upscales past
// native width (BUILD_BRIEF §4.5) and no image causes layout shift (§9.9).

export type PhotoOrientation = "portrait" | "landscape" | "square";

export interface Photo {
  slug: string;
  width: number;
  height: number;
  orientation: PhotoOrientation;
}

export const PHOTOS = {
${rows.join("\n")}
} as const satisfies Record<string, Photo>;

export type PhotoSlug = keyof typeof PHOTOS;

/** Path to the supplied JPEG. next/image derives AVIF/WebP + srcset from it. */
export function photoSrc(slug: PhotoSlug): string {
  return \`/photos/\${slug}.jpg\`;
}

/** Photos the brief (§8) designates for full-width bands — all landscape. */
export const BAND_PHOTOS = [
  "team-uba-marketplace",
  "rooftop-terrace-machine-scrubbing",
  "post-construction-before-debris",
  "window-grille-wiping",
] as const satisfies readonly PhotoSlug[];

/** §3.3 — on hold until a matching "before" exists. Never render. */
export const ON_HOLD: readonly string[] = ["polished-tile-floor-after-cleaning"];
`
);
console.log(`src/lib/photos.ts regenerated — ${files.length} photos`);
