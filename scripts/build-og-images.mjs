import sharp from "sharp";
import { mkdirSync, existsSync, writeFileSync, readFileSync } from "fs";
import path from "path";

/**
 * Generate Open Graph crops at 1.91:1 and record their REAL dimensions.
 *
 * Two faults this fixes, both from SITE_REVIEW 3.7:
 *
 * 1. Every page declared og:image width 1200 height 630 while pointing at
 *    portrait photographs of entirely different shapes. Platforms were told one
 *    size and served another, which is what makes a share card crop oddly.
 *
 * 2. The naive fix - resize everything to 1200x630 - would upscale five of the
 *    eleven sources, and BUILD_BRIEF section 8 forbids upscaling a supplied
 *    photograph. So each crop is made at the largest 1.91:1 rectangle the
 *    source actually contains, capped at 1200x630, and the true dimensions are
 *    written to src/lib/og.ts for seo.tsx to declare.
 *
 * Run: node scripts/build-og-images.mjs
 */
const SRC = "public/photos";
const OUT = "public/og";
const RATIO = 1200 / 630;

mkdirSync(OUT, { recursive: true });

// Every photo used as a page's OG image.
const slugs = [...new Set(
  [...readFileSync("src/lib/ogsources.json", "utf8").matchAll(/"([a-z0-9-]+)"/g)].map((m) => m[1])
)];

const manifest = {};
for (const slug of slugs) {
  const src = path.join(SRC, slug + ".jpg");
  if (!existsSync(src)) { console.log("MISSING", src); continue; }
  const m = await sharp(src).metadata();

  // Largest 1.91:1 box that fits inside the source, then capped at 1200x630.
  let w = Math.min(m.width, Math.round(m.height * RATIO));
  let h = Math.round(w / RATIO);
  if (w > 1200) { w = 1200; h = 630; }

  await sharp(src)
    .resize(w, h, { fit: "cover", position: "attention", withoutEnlargement: true })
    .jpeg({ quality: 82, mozjpeg: true })
    .toFile(path.join(OUT, slug + ".jpg"));

  const o = await sharp(path.join(OUT, slug + ".jpg")).metadata();
  manifest[slug] = { w: o.width, h: o.height };
  console.log(`${slug}  ${m.width}x${m.height} -> ${o.width}x${o.height}${o.width < 1200 ? "  (source too small for 1200w; not upscaled)" : ""}`);
}

writeFileSync(
  "src/lib/og.ts",
  `// GENERATED by scripts/build-og-images.mjs — do not edit by hand.\n` +
  `// Real pixel dimensions of each /og/*.jpg crop, so og:image:width and\n` +
  `// og:image:height describe the file that is actually served.\n` +
  `export const OG_SIZES: Record<string, { w: number; h: number }> = ${JSON.stringify(manifest, null, 2)};\n`
);
console.log(`\nwrote src/lib/og.ts with ${Object.keys(manifest).length} entries`);
